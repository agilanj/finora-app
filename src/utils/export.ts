import { jsPDF } from "jspdf";
import * as XLSX from "xlsx";
import { Transaction, Account } from "../types/finance";
import { BRAND } from "../config/brand";

export interface ExportFilterOptions {
  category?: string;
  periodLabel: string;
  startDate?: string;
  endDate?: string;
  accountId?: string;
  transactionType?: string;
}

export function generatePDFReport(
  transactions: Transaction[],
  accounts: Account[],
  filters: ExportFilterOptions,
  currencySymbol = "Rs."
): { blob: Blob; filename: string } {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const currencyLabel = currencySymbol === "₹" ? "Rs." : currencySymbol;

  // Helper for crisp Indian / standard number formatting with 2 decimals
  const formatAmt = (val: number): string => {
    return `${currencyLabel} ${val.toLocaleString("en-IN", {
      minimumFractionDigits: 2,
      maximumFractionDigits: 2,
    })}`;
  };

  // 1. Clean Monochrome Bank Statement Header (No colors, pure official typography)
  doc.setTextColor(15, 23, 42); // slate-900
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.text(BRAND.name.toUpperCase(), 14, 18);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(71, 85, 105); // slate-600
  doc.text("ACCOUNT STATEMENT & TRANSACTION LEDGER", 14, 24);
  doc.text(`Statement Period: ${filters.periodLabel}`, 14, 29);

  // Right-aligned Generation Metadata
  const generatedTime = new Date().toLocaleDateString("en-IN", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "2-digit",
    minute: "2-digit",
  });
  doc.setFontSize(8);
  doc.text(`Generated: ${generatedTime}`, 196, 18, { align: "right" });
  doc.text("Status: Verified Ledger", 196, 23, { align: "right" });
  doc.text("Format: Official Monochrome", 196, 28, { align: "right" });

  // Divider Line
  doc.setDrawColor(30, 41, 59); // slate-800
  doc.setLineWidth(0.4);
  doc.line(14, 33, 196, 33);

  // 2. Summary Particulars Box (Crisp grayscale border, no colorful fills)
  let totalCredits = 0;
  let totalDebits = 0;

  transactions.forEach((tx) => {
    if (tx.type === "income") totalCredits += tx.amount;
    else if (tx.type === "expense") totalDebits += tx.amount;
    else if (tx.type === "transfer") totalDebits += tx.amount;
  });

  const netBalance = totalCredits - totalDebits;

  doc.setDrawColor(203, 213, 225); // slate-300
  doc.setLineWidth(0.25);
  doc.rect(14, 37, 182, 19);

  doc.setFontSize(7.5);
  doc.setTextColor(100, 116, 139);
  doc.setFont("helvetica", "bold");
  doc.text("TOTAL CREDITS (+)", 18, 43);
  doc.text("TOTAL DEBITS (-)", 65, 43);
  doc.text("NET CASHFLOW", 115, 43);
  doc.text("RECORD COUNT", 165, 43);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10.5);
  doc.setTextColor(15, 23, 42); // Clean dark text
  doc.text(formatAmt(totalCredits), 18, 51);
  doc.text(formatAmt(totalDebits), 65, 51);
  doc.text((netBalance >= 0 ? "+" : "") + formatAmt(netBalance), 115, 51);
  doc.text(`${transactions.length} Transactions`, 165, 51);

  // 3. Transactions Table Header (Monochrome bank table)
  let y = 63;
  doc.setDrawColor(51, 65, 85);
  doc.setLineWidth(0.3);
  doc.line(14, y, 196, y);

  doc.setFontSize(7.5);
  doc.setFont("helvetica", "bold");
  doc.setTextColor(15, 23, 42);
  doc.text("DATE", 16, y + 4.5);
  doc.text("PARTICULARS / DESCRIPTION", 38, y + 4.5);
  doc.text("CATEGORY", 96, y + 4.5);
  doc.text("ACCOUNT", 132, y + 4.5);
  doc.text("TYPE", 162, y + 4.5);
  doc.text("AMOUNT", 194, y + 4.5, { align: "right" });

  doc.line(14, y + 6.5, 196, y + 6.5);
  y += 7;

  doc.setFont("helvetica", "normal");
  const accountMap = new Map(accounts.map((a) => [a.id, a.name]));

  let pageNumber = 1;

  // 4. Rows (Clean alternating white/light-gray without card colors)
  transactions.forEach((tx) => {
    if (y > 275) {
      // Page footer for current page
      doc.setFontSize(7);
      doc.setTextColor(148, 163, 184);
      doc.text("This document is a certified transaction record generated by FINORA.", 14, 288);
      doc.text(`Page ${pageNumber}`, 196, 288, { align: "right" });

      doc.addPage();
      pageNumber++;
      y = 18;

      // Re-draw table header on subsequent pages
      doc.setDrawColor(51, 65, 85);
      doc.setLineWidth(0.3);
      doc.line(14, y, 196, y);
      doc.setFontSize(7.5);
      doc.setFont("helvetica", "bold");
      doc.setTextColor(15, 23, 42);
      doc.text("DATE", 16, y + 4.5);
      doc.text("PARTICULARS / DESCRIPTION", 38, y + 4.5);
      doc.text("CATEGORY", 96, y + 4.5);
      doc.text("ACCOUNT", 132, y + 4.5);
      doc.text("TYPE", 162, y + 4.5);
      doc.text("AMOUNT", 194, y + 4.5, { align: "right" });
      doc.line(14, y + 6.5, 196, y + 6.5);
      y += 7;
      doc.setFont("helvetica", "normal");
    }

    doc.setFontSize(7.5);
    doc.setTextColor(51, 65, 85);
    doc.text(tx.date, 16, y + 4);

    // Description
    const descText = tx.description.length > 34 ? tx.description.slice(0, 32) + ".." : tx.description;
    doc.setTextColor(15, 23, 42);
    doc.text(descText, 38, y + 4);

    // Category
    const catText = tx.category.length > 20 ? tx.category.slice(0, 18) + ".." : tx.category;
    doc.setTextColor(71, 85, 105);
    doc.text(catText, 96, y + 4);

    // Account
    const accName = accountMap.get(tx.accountId) || "Bank Account";
    doc.text(accName.slice(0, 16), 132, y + 4);

    // Type & Amount in clean dark text
    if (tx.type === "income") {
      doc.text("Credit", 162, y + 4);
      doc.setFont("helvetica", "bold");
      doc.text(`+${formatAmt(tx.amount)}`, 194, y + 4, { align: "right" });
    } else if (tx.type === "expense") {
      doc.text("Debit", 162, y + 4);
      doc.setFont("helvetica", "bold");
      doc.text(`-${formatAmt(tx.amount)}`, 194, y + 4, { align: "right" });
    } else {
      doc.text("Transfer", 162, y + 4);
      doc.setFont("helvetica", "bold");
      doc.text(formatAmt(tx.amount), 194, y + 4, { align: "right" });
    }

    doc.setFont("helvetica", "normal");

    // Thin row divider
    doc.setDrawColor(241, 245, 249);
    doc.setLineWidth(0.15);
    doc.line(14, y + 5.5, 196, y + 5.5);

    y += 5.8;
  });

  // Final Page Footer
  doc.setFontSize(7);
  doc.setTextColor(148, 163, 184);
  doc.text("This document is a certified transaction record generated by FINORA.", 14, 288);
  doc.text(`Page ${pageNumber}`, 196, 288, { align: "right" });

  const filename = `FINORA_Bank_Statement_${filters.periodLabel.replace(/\s+/g, "_")}.pdf`;
  const blob = doc.output("blob");
  return { blob, filename };
}

export function generateExcelReport(
  transactions: Transaction[],
  accounts: Account[],
  filters: ExportFilterOptions,
  currencySymbol = "₹"
): { blob: Blob; filename: string } {
  const accountMap = new Map(accounts.map((a) => [a.id, a.name]));

  // Sheet 1: Transactions
  const txData = transactions.map((t) => ({
    ID: t.id,
    Date: t.date,
    Time: t.time || "",
    Description: t.description,
    Category: t.category,
    Type: t.type.toUpperCase(),
    Amount: t.amount,
    Account: accountMap.get(t.accountId) || t.accountId,
    "Payment Method": t.paymentMethod,
    Notes: t.notes || "",
  }));

  const wb = XLSX.utils.book_new();
  const ws1 = XLSX.utils.json_to_sheet(txData);
  XLSX.utils.book_append_sheet(wb, ws1, "Transactions");

  // Sheet 2: Account Balances
  const accData = accounts.map((a) => ({
    "Account Name": a.name,
    "Bank Name": a.bankName,
    Type: a.accountType.toUpperCase(),
    Balance: a.balance,
    Currency: a.currency,
    "Masked No": a.maskedNumber,
  }));
  const ws2 = XLSX.utils.json_to_sheet(accData);
  XLSX.utils.book_append_sheet(wb, ws2, "Accounts");

  const wbout = XLSX.write(wb, { bookType: "xlsx", type: "array" });
  const blob = new Blob([wbout], { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  const filename = `FINORA_Report_${filters.periodLabel.replace(/\s+/g, "_")}_${Date.now()}.xlsx`;

  return { blob, filename };
}

export function generateCSVReport(
  transactions: Transaction[],
  accounts: Account[],
  filters: ExportFilterOptions
): { blob: Blob; filename: string } {
  const accountMap = new Map(accounts.map((a) => [a.id, a.name]));

  const headers = ["ID", "Date", "Description", "Category", "Type", "Amount", "Account", "Payment Method", "Notes"];
  const rows = transactions.map((t) => [
    `"${t.id}"`,
    `"${t.date}"`,
    `"${t.description.replace(/"/g, '""')}"`,
    `"${t.category}"`,
    `"${t.type}"`,
    t.amount,
    `"${accountMap.get(t.accountId) || t.accountId}"`,
    `"${t.paymentMethod}"`,
    `"${(t.notes || "").replace(/"/g, '""')}"`,
  ]);

  const csvContent = [headers.join(","), ...rows.map((r) => r.join(","))].join("\n");
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const filename = `FINORA_Transactions_${filters.periodLabel.replace(/\s+/g, "_")}_${Date.now()}.csv`;

  return { blob, filename };
}

export function downloadBlob(blob: Blob, filename: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
